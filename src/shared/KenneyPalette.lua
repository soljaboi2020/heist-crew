    HEIST CREW — KenneyPalette (GENERATED, do not hand-edit)
    ────────────────────────────────────────────────
    The Kenney furniture-kit ships NO texture images. It colours models with
    named flat materials defined as RGB in the .mtl files, and Roblox's FBX
    importer drops those — every piece arrives white. (Confirmed 2026-09-22:
    Malachi imported desk.fbx and got a white desk.)

    This table restores them. Generated by tools/gen_palette.py, which parses
    all 140 .mtl files for their real Kd values and COUNTS FACES per material
    in the matching .obj, so "dominant" is measured rather than assumed.

    The dungeon and factory kits do NOT need this — they ship texture atlases
    and import with their colour intact.
--]]


-- Tint an imported MeshPart to match the original Kenney colours.
-- Safe to call on anything: an unknown name is left untouched rather than
-- silently painted the wrong colour.
function Palette.apply(part, modelName)
    local matName = Palette.MODELS[modelName]
    if not matName then return false end
    local entry = Palette.MATERIALS[matName]
    if not entry then return false end
    part.Color = entry.color
    part.Material = entry.material
    return true
end

return Palette

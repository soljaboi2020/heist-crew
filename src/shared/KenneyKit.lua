--[[
    HEIST CREW — KenneyKit (GENERATED — do not hand-edit)
    ────────────────────────────────────────────────
    Data for the three Kenney CC0 packs in src/assets/_kenney/.
    Regenerate with:  python3 tools/gen_kit_data.py

    TWO PROBLEMS THIS SOLVES, both found the hard way on 2026-09-22:

    1. COLOUR — the furniture kit ships NO texture images. It colours models
       with named flat materials whose RGB lives in the .mtl files, and
       Roblox's FBX importer drops them. Malachi imported desk.fbx and got a
       white desk. SIZES/MATERIALS below restore the intended colour.
       The dungeon and factory kits do NOT need this — they ship texture
       atlases and import coloured.

    2. SCALE — the kits are NOT at a common scale, so there is no single
       multiplier. Measured from .obj bounding boxes against real-world sizes:
         • dungeon + factory : 1 unit = 1 metre
         • furniture         : 1 unit ≈ 1.9 metres (a miniature kit)
       SIZES holds every model already converted to STUDS (1 stud = 0.28 m),
       so placement code can set MeshPart.Size directly and the mesh scales to
       fit — whatever scale it happened to import at.
--]]


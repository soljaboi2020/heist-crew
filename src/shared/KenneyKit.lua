-- Size an imported MeshPart correctly. Returns false (and changes nothing) if
-- the model is unknown, rather than guessing a size.
function KenneyKit.applySize(part, kit, modelName)
    local kitTable = KenneyKit.SIZES[kit]
    if not kitTable then return false end
    local size = kitTable[modelName]
    if not size then return false end
    part.Size = size
    return true
end

-- Restore a furniture piece's colour. No-op on the dungeon/factory kits, which
-- carry their own textures and must NOT be tinted.
function KenneyKit.applyColor(part, modelName)
    local matName = KenneyKit.FURNITURE_MATERIAL[modelName]
    if not matName then return false end
    local entry = KenneyKit.MATERIALS[matName]
    if not entry then return false end
    part.Color = entry.color
    part.Material = entry.material
    return true
end

return KenneyKit
